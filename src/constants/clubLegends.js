export function getClubLegendTheme(teamTag, fallbackColor = '#D4AF37') {
  const tag = (teamTag || '').toUpperCase();
  const base = CLUB_LEGEND_THEMES[tag];

  if (base) {
    return {
      ...base,
      metalFinish: METAL_FINISHES[base.metal] || METAL_FINISHES.gold,
      patternImage: base.patternImage || null,
    };
  }

  const primary = TEAM_COLORS[tag] || fallbackColor || '#D4AF37';
  const teamInfo = getTeamInfo(tag);
  const displayName = teamInfo?.name || tag || 'CLUB';

  return {
    primary,
    secondary: '#D4AF37',
    accent: '#FFFFFF',
    bgDark: '#0D0E14',
    bgMid: '#1E2233',
    borderGold: '#D4AF37',
    glow: `${primary}73`,
    tagLine: `${tag || displayName.toUpperCase()} LEGEND`,
    metal: 'gold',
    metalFinish: METAL_FINISHES.gold,
    patternImage: null,
  };
}

export function isClubLegendCard(card) {
  if (!card) return false;
  return (
    card.rarity === 'Légende de club' ||
    card.rarity === 'Club Legend' ||
    card.cardType === 'club_legend' ||
    card.cardType === 'legend' ||
    card.isClubLegend === true ||
    Boolean(card.legendTeam)
  );
}