export const CHAMPION_BY_ID = ALL_CHAMPIONS.reduce((acc, c) => {
  acc[c.id] = c;
  return acc;
}, {});

export function getChampionById(id) {
  if (!id) return null;
  const normalized = id.toLowerCase().replace(/[^a-z0-9]/g, '_').replace(/_+/g, '_').replace(/^_|_$/g, '');
  return CHAMPION_BY_ID[normalized] || ALL_CHAMPIONS.find(c => c.id === id || c.name.toLowerCase() === id.toLowerCase()) || null;
}

export function getChampionsByRole(role) {
  if (!role) return ALL_CHAMPIONS;
  const r = role.toLowerCase();
  return ALL_CHAMPIONS.filter(c => c.roles.some(cr => cr.toLowerCase() === r));
}
